/**
 * Evidence per (company, service), taken from the design artboards (Prospects, Company, Feed, Quality).
 *
 * `targets` is the strength s_q each question should reach. The seed splits it over the question's signals
 * (noisy-OR, by `share`) and stores a per-signal factor, so the scoring engine reproduces the design numbers:
 * with profile v3 (weights 3/2/1, tau_intent 3, tau_risk 2, fit^0.4 × intent^0.6 × (1 − 0.5 × risk)) DHL gets
 * Priority 71 · Fit 100 · Intent 81 · Risk 38, Nordhavn 79 · 100 · 77 · 14, and so on.
 */
import type { SignalFlag, SourceType, Strength } from "@/api/generated/model"

export interface SignalSpec {
  q: string
  quote: string
  summary: string
  /** SignalItem.source_name, e.g. "dhl.com", "Workday careers". */
  src: string
  type: SourceType
  url: string
  /** Title of the scanned document (defaults to the summary). */
  title?: string
  /** Collector that fetched the document (DocumentOut.source_name). */
  doc?: string
  /** event_date, days before now; null = undated. */
  date: number | null
  /** published_at, days before now (defaults to `date`). */
  pub?: number
  strength: Strength
  conf: number
  flags?: SignalFlag[]
  /** detected_at, days before now (default: one day after publication). */
  det?: number
  /** detected_at, hours before now (wins over `det`). */
  detH?: number
  /** Share of the question's strength carried by this signal (default 1). */
  share?: number
  /** Voted "incorrect" by a user: stored, but never shown or scored. */
  rejected?: boolean
  lang?: string
}

export interface DerivedSpec {
  derived: "nis2" | "dora"
  share?: number
}

export interface LeadSpec {
  company: string
  service: "ia" | "cyber"
  targets: Record<string, number>
  signals: (SignalSpec | DerivedSpec)[]
  /** Older score points, newest first: [days before now, priority]. Generated when omitted. */
  history?: [number, number][]
}

